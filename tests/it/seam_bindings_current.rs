//! The seam bindings' staleness gate: a fresh export of the TS↔Rust seam family
//! byte-compares against the committed `sdk/src/generated/` files. A Rust-side change
//! with stale bindings fails here loudly (the fail-loud invariant), never ships silent
//! drift.
//!
//! The family is two things, not one: the `ts-rs` **types**, and the modules of
//! **values** — temper's gate commands (0073) and its tap-hook registrations, each
//! generated from the engine's own table so the SDK imports the binding instead of
//! restating it.
//!
//! The committed files are *generated*, never hand-edited: rerun this test with
//! `BLESS_SEAM_BINDINGS=1` to rewrite `sdk/src/generated/` from the current Rust
//! sources, then commit the diff.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

use temper::builtin_kind::{TAP_HOOK_BINDINGS, TapHookBinding};
use temper::compose::Verifier;
use temper::contract::Shape;
use temper::drift::{
    AssemblyFactRow, BoundRow, CharsetRow, ClauseRow, CollectionAddressRow, CollectionEntryRow,
    CollectionEntryWire, CountBoundRow, Declarations, DegreeBoundRow, EdgeBoundRow, IncludeRow,
    InputRow, KindFactRow, LayoutRegionRow, LayoutRow, MentionRow, NestedMemberRow, Payload,
    PayloadMember, RangeBoundRow, RegistrationRow, RequirementRow, SatisfiesRow,
    SectionContainsRow, SettingsRow, TemplateRow,
};
use temper::extract::{
    EmbeddedMember, EmbeddedMemberCollectionEntry, FeatureValue, Features, FencedBlock, Section,
    ValueType,
};
use temper::install::GATE_COMMAND_BINDINGS;

/// The one binding home — the directory every seam type exports into.
fn generated_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("sdk/src/generated")
}

/// The export config the bindings ride: `.js` import specifiers, matching the
/// SDK's NodeNext ESM resolution (a generated cross-import is `./Other.js`).
fn config() -> Config {
    Config::default().with_import_extension(Some("js"))
}

/// The barrel's note — the generated `index.ts` is code's, never a hand edit.
const BARREL_NOTE: &str =
    "// This file re-exports the generated seam bindings. Do not edit this file manually.\n";

const GATE_COMMANDS_FILE: &str = "gate-commands.ts";
const TAP_HOOKS_FILE: &str = "tap-hooks.ts";

/// One generated file carrying **values** rather than a `ts-rs` type: the barrel
/// re-exports it with `export { … }` and it is held out of the `export type` loop. Each
/// stem is hyphen-cased on purpose — every sibling is a type file named for its type, and
/// a `gate-commands` stem cannot be mistaken for one.
struct ValuesModule {
    /// The committed filename under the binding home.
    file: &'static str,
    /// The module's whole bytes, written from the engine's own table.
    source: fn() -> String,
    /// The names the barrel re-exports from it, in the module's own order.
    exports: fn() -> Vec<&'static str>,
    /// A respelling of the generated bytes that no engine table would produce — the drift
    /// this gate exists to catch, driven over each module in turn.
    drift: (&'static str, &'static str),
}

/// Every values module in the seam family, in the barrel's own re-export order.
const VALUES_MODULES: [ValuesModule; 2] = [
    ValuesModule {
        file: GATE_COMMANDS_FILE,
        source: gate_commands_module,
        exports: gate_command_exports,
        drift: ("temper guard .", "temper guard"),
    },
    ValuesModule {
        file: TAP_HOOKS_FILE,
        source: tap_hooks_module,
        exports: tap_hook_exports,
        drift: ("PostToolUse", "PreToolUse"),
    },
];

/// Whether `file` is a values module rather than a `ts-rs` type binding.
fn is_values_module(file: &str) -> bool {
    VALUES_MODULES.iter().any(|module| module.file == file)
}

/// A generated values module's header — the one note that keeps a reader from hand-editing
/// bytes the next `cargo test` overwrites.
fn values_header(subject: &str) -> String {
    format!("// This file carries temper's {subject}. Do not edit this file manually.\n")
}

/// The gate-commands module's exported names — [`GATE_COMMAND_BINDINGS`]'s own order.
fn gate_command_exports() -> Vec<&'static str> {
    GATE_COMMAND_BINDINGS
        .iter()
        .map(|(binding, _)| *binding)
        .collect()
}

/// The gate-commands module's bytes: temper's gate commands, written from the engine's own
/// [`GATE_COMMAND_BINDINGS`] table — one home for the bytes and one for the names, so the
/// SDK copy is machine-written and this gate is what keeps it honest.
fn gate_commands_module() -> String {
    let mut src = values_header("gate commands, generated from the engine's own constants");
    for (binding, command) in GATE_COMMAND_BINDINGS {
        src.push_str(&format!("export const {binding} = {};\n", literal(command)));
    }
    src
}

/// The tap-hooks module's single exported name: the whole table rides one record, since a
/// consumer looks an author-supplied event name up in it rather than importing one row.
fn tap_hook_exports() -> Vec<&'static str> {
    vec![TAP_EVENT_HOOKS]
}

/// The binding the tap-hooks module exports its table under.
const TAP_EVENT_HOOKS: &str = "TAP_EVENT_HOOKS";

/// The tap-hooks module's bytes: every documented tap event paired with the `hooks.<Event>`
/// registration and matcher its tap hook takes, written from the engine's own
/// [`TAP_HOOK_BINDINGS`] table — so the SDK's `TELEMETRY_EVENT_HOOKS` reads the pairing
/// rather than restating it across the seam.
fn tap_hooks_module() -> String {
    let mut src = values_header("tap-hook registrations, generated from the engine's own table");
    src.push_str(&format!("export const {TAP_EVENT_HOOKS} = {{\n"));
    for TapHookBinding {
        name,
        event,
        matcher,
    } in &TAP_HOOK_BINDINGS
    {
        src.push_str(&format!(
            "  {}: {{ event: {}, matcher: {} }},\n",
            literal(name),
            literal(event),
            literal(matcher)
        ));
    }
    src.push_str("} as const;\n");
    src
}

/// `value` as a TS string literal. JSON string encoding is TS string encoding for these
/// bytes, and a gate command carries embedded quotes — so the escaping is `serde_json`'s,
/// never hand-rolled.
fn literal(value: &str) -> String {
    serde_json::to_string(value).expect("a seam value serializes infallibly")
}

/// One seam type's committed filename paired with its freshly-exported bytes.
fn binding<T: TS + 'static>(cfg: &Config) -> (String, String) {
    let path = <T as TS>::output_path()
        .expect("a seam binding type declares an output path")
        .to_string_lossy()
        .into_owned();
    let content =
        <T as TS>::export_to_string(cfg).expect("a seam binding type exports to a string");
    (path, content)
}

/// Every generated file's name → its freshly-exported bytes, plus the `index.ts` barrel
/// re-exporting each. The list is the whole TS↔Rust seam: the extraction feature family,
/// the payload/declaration-row family, and every values module.
fn fresh_bindings() -> BTreeMap<String, String> {
    let cfg = config();
    let mut files = BTreeMap::new();

    macro_rules! collect {
        ($($ty:ty),* $(,)?) => {
            $(
                let (path, content) = binding::<$ty>(&cfg);
                files.insert(path, content);
            )*
        };
    }

    collect!(
        // The clause vocabulary's own closed argument sets (`src/contract.rs`) — declared
        // once in Rust and generated across, so a member cannot be added on one side.
        Shape,
        // The requirement's typed verifier species union (`src/compose.rs`).
        Verifier,
        // Extraction feature family (`src/extract.rs`).
        ValueType,
        FeatureValue,
        Section,
        FencedBlock,
        EmbeddedMember,
        EmbeddedMemberCollectionEntry,
        Features,
        // Payload / declaration-row family (`src/drift.rs`).
        Payload,
        PayloadMember,
        Declarations,
        KindFactRow,
        TemplateRow,
        CollectionAddressRow,
        LayoutRow,
        LayoutRegionRow,
        ClauseRow,
        BoundRow,
        CharsetRow,
        RangeBoundRow,
        SectionContainsRow,
        RequirementRow,
        CountBoundRow,
        DegreeBoundRow,
        EdgeBoundRow,
        SatisfiesRow,
        MentionRow,
        IncludeRow,
        InputRow,
        NestedMemberRow,
        CollectionEntryRow,
        CollectionEntryWire,
        RegistrationRow,
        SettingsRow,
        AssemblyFactRow,
    );

    for module in &VALUES_MODULES {
        files.insert(module.file.to_owned(), (module.source)());
    }

    // The barrel re-exports each generated type, one `export type` per file, in the same
    // sorted order the map already keeps — then each values module, whose exports are
    // values: an `export type { gate-commands }` line is neither its shape nor even TS, so
    // the values modules are held out of the type loop and re-exported by name.
    let mut barrel = String::from(BARREL_NOTE);
    for path in files.keys().filter(|path| !is_values_module(path)) {
        let stem = path.trim_end_matches(".ts");
        barrel.push_str(&format!("export type {{ {stem} }} from \"./{stem}.js\";\n"));
    }
    for module in &VALUES_MODULES {
        let stem = module.file.trim_end_matches(".ts");
        barrel.push_str(&format!(
            "export {{ {} }} from \"./{stem}.js\";\n",
            (module.exports)().join(", ")
        ));
    }
    files.insert("index.ts".to_owned(), barrel);
    files
}

/// The staleness readings between a fresh export and what is committed — one line per
/// disagreement, empty when the two sides are byte-equal. Factored out of the disk
/// comparison so the gate's own refusal is pinned over a hand-edited copy without ever
/// writing to the committed tree.
fn staleness(
    fresh: &BTreeMap<String, String>,
    committed: &BTreeMap<String, String>,
) -> Vec<String> {
    let mut stale: Vec<String> = Vec::new();
    for (name, content) in fresh {
        match committed.get(name) {
            Some(on_disk) if on_disk == content => {}
            Some(_) => stale.push(format!("`{name}` differs from a fresh export")),
            None => stale.push(format!("`{name}` is missing from the binding home")),
        }
    }
    for name in committed.keys() {
        if !fresh.contains_key(name) {
            stale.push(format!(
                "`{name}` is an orphan the current types no longer export"
            ));
        }
    }
    stale
}

/// The `.ts` files currently committed under the binding home.
fn committed_files(dir: &Path) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    let entries = std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("read the binding home `{}`: {e}", dir.display()));
    for entry in entries {
        let entry = entry.expect("a directory entry");
        let name = entry.file_name().to_string_lossy().into_owned();
        if name.ends_with(".ts") {
            let content = std::fs::read_to_string(entry.path())
                .unwrap_or_else(|e| panic!("read `{name}`: {e}"));
            files.insert(name, content);
        }
    }
    files
}

#[test]
fn committed_bindings_byte_match_a_fresh_export() {
    let dir = generated_dir();
    let fresh = fresh_bindings();

    if std::env::var_os("BLESS_SEAM_BINDINGS").is_some() {
        std::fs::create_dir_all(&dir).expect("create the binding home");
        // Drop any committed `.ts` file the current type set no longer produces,
        // then write the fresh set — a retired type leaves no orphan behind.
        for name in committed_files(&dir).keys() {
            if !fresh.contains_key(name) {
                std::fs::remove_file(dir.join(name)).expect("remove a stale binding");
            }
        }
        for (name, content) in &fresh {
            std::fs::write(dir.join(name), content).expect("write a fresh binding");
        }
        return;
    }

    let committed = committed_files(&dir);
    // Vacuity pin: the whole generated family is under the compare, every values module
    // included — a gate that judged an empty set would pass on anything.
    assert!(
        fresh.len() > VALUES_MODULES.len() + 1
            && VALUES_MODULES
                .iter()
                .all(|module| fresh.contains_key(module.file)),
        "the fresh set is the whole seam family, got: {:?}",
        fresh.keys().collect::<Vec<_>>()
    );

    let stale = staleness(&fresh, &committed);
    assert!(
        stale.is_empty(),
        "sdk/src/generated is stale — rerun with BLESS_SEAM_BINDINGS=1 to regenerate, then \
         commit the diff:\n  {}",
        stale.join("\n  "),
    );
}

#[test]
fn a_hand_edited_values_module_reads_stale_like_any_other_binding() {
    let fresh = fresh_bindings();

    // Vacuity pin: every engine row reaches its module's bytes, so the refusals below are
    // over the real generated content rather than an empty table's.
    for (binding, command) in GATE_COMMAND_BINDINGS {
        let module = &fresh[GATE_COMMANDS_FILE];
        assert!(module.contains(binding), "got:\n{module}");
        assert!(module.contains(&literal(command)), "got:\n{module}");
    }
    assert!(!TAP_HOOK_BINDINGS.is_empty());
    for TapHookBinding {
        name,
        event,
        matcher,
    } in &TAP_HOOK_BINDINGS
    {
        let module = &fresh[TAP_HOOKS_FILE];
        let row = format!(
            "  {}: {{ event: {}, matcher: {} }},",
            literal(name),
            literal(event),
            literal(matcher)
        );
        assert!(module.contains(&row), "got:\n{module}");
    }

    for module in &VALUES_MODULES {
        let stem = module.file.trim_end_matches(".ts");
        let line = format!(
            "export {{ {} }} from \"./{stem}.js\";",
            (module.exports)().join(", ")
        );
        assert!(
            fresh["index.ts"].contains(&line),
            "the barrel re-exports `{stem}` as values, got:\n{}",
            fresh["index.ts"]
        );

        // A hand edit to the generated bytes — the drift this gate exists to catch. It
        // reads exactly as a stale `ts-rs` binding does: same reading, same remedy.
        let (from, to) = module.drift;
        let source = &fresh[module.file];
        assert!(source.contains(from), "the drift lands, got:\n{source}");
        let mut edited = fresh.clone();
        edited.insert(module.file.to_owned(), source.replace(from, to));
        assert_eq!(
            staleness(&fresh, &edited),
            vec![format!("`{}` differs from a fresh export", module.file)],
        );
    }
}
